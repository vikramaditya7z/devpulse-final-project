/**
 * Unified endpoint to get any report by ID (personal or workspace)
 * GET /api/reports/:id
 * Protected by requireAuth
 */
const getReportById = async (req, res, next) => {
  try {
    const { id } = req.params;

    if (!mongoose.Types.ObjectId.isValid(id)) {
      return res.status(400).json({
        success: false,
        error: {
          code: 'INVALID_REPORT_ID',
          message: 'Invalid report identifier format.'
        }
      });
    }

    const report = await HealthReport.findById(id)
      .populate('createdBy', 'name email')
      .populate('workspace', 'name');

    if (!report) {
      return res.status(404).json({
        success: false,
        error: {
          code: 'REPORT_NOT_FOUND',
          message: 'Health report not found.'
        }
      });
    }

    // Authorization checks based on report scope:
    if (report.scope === 'personal') {
      if (report.user.toString() !== req.user.id) {
        return res.status(403).json({
          success: false,
          error: {
            code: 'FORBIDDEN',
            message: 'You are not authorized to access this personal report.'
          }
        });
      }
    } else if (report.scope === 'workspace') {
      const membership = await WorkspaceMember.findOne({
        workspace: report.workspace._id || report.workspace,
        user: req.user.id
      });

      if (!membership) {
        return res.status(403).json({
          success: false,
          error: {
            code: 'NOT_A_WORKSPACE_MEMBER',
            message: 'You are not an authorized member of the workspace this report belongs to.'
          }
        });
      }
    }

    return res.status(200).json({
      success: true,
      data: {
        report
      }
    });
  } catch (error) {
    return next(error);
  }
};

