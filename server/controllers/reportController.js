/**
 * Generate a persistent personal health report for a repository saved by current user
 * POST /api/reports/personal
 * Protected by requireAuth
 */
const generatePersonalReport = async (req, res, next) => {
  try {
    const { repoId } = req.body;

    if (!repoId || !mongoose.Types.ObjectId.isValid(repoId)) {
      return res.status(400).json({
        success: false,
        error: {
          code: 'INVALID_REPO_ID',
          message: 'Valid repository identifier is required.'
        }
      });
    }

    // Verify repository exists on user's personal dashboard
    const savedRepo = await SavedRepository.findOne({
      _id: repoId,
      user: req.user.id,
      scope: 'personal'
    });

    if (!savedRepo) {
      return res.status(404).json({
        success: false,
        error: {
          code: 'REPO_NOT_FOUND',
          message: 'Saved repository not found on your personal dashboard.'
        }
      });
    }

    // Fetch live GitHub data
    let rawData;
    try {
      rawData = await githubService.getRawRepoData(savedRepo.owner, savedRepo.repo);
    } catch (apiError) {
      return res.status(apiError.statusCode || 502).json({
        success: false,
        error: {
          code: apiError.code || 'GITHUB_ERROR',
          message: apiError.message,
          details: apiError.details
        }
      });
    }

    // Deterministic analysis
    const analysis = analysisService.analyzeRepository(rawData);

    // Create immutable persistent report record
    const report = await HealthReport.create({
      repository: {
        owner: savedRepo.owner,
        repo: savedRepo.repo,
        fullName: savedRepo.fullName,
        url: savedRepo.url,
        description: savedRepo.description,
        defaultBranch: savedRepo.defaultBranch
      },
      scope: 'personal',
      user: req.user.id,
      createdBy: req.user.id,
      metrics: analysis.metrics,
      findings: analysis.findings,
      reportingPeriodDays: analysis.reportingPeriodDays || 30,
      status: 'complete',
      generatedAt: new Date()
    });

    return res.status(201).json({
      success: true,
      data: {
        report
      }
    });
  } catch (error) {
    return next(error);
  }
};

