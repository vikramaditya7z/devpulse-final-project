import React, { useState, useEffect } from 'react';
import { useParams, Link, useNavigate } from 'react-router-dom';
import { reportApi } from '../services/api';
import { MetricCard } from '../components/MetricCard';
import { FindingsSection } from '../components/FindingsSection';
import {
  ArrowLeft,
  FileText,
  Clock,
  Shield,
  User,
  AlertCircle,
  ExternalLink,
  Star,
  GitPullRequest,
  CheckCircle2,
  GitCommit,
  AlertTriangle
} from 'lucide-react';

export const ReportDetail = () => {
  const { id } = useParams();
  const navigate = useNavigate();

  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    const fetchReport = async () => {
      try {
        setLoading(true);
        setError(null);
        const data = await reportApi.getReportById(id);
        setReport(data.report);
      } catch (err) {
        setError(err.message || 'Failed to load report snapshot.');
      } finally {
        setLoading(false);
      }
    };

    fetchReport();
  }, [id]);

  if (loading) {
    return (
      <div className="max-w-7xl mx-auto px-4 py-16 flex flex-col items-center justify-center min-h-[50vh]">
        <div className="w-8 h-8 border-4 border-emerald-600 border-t-transparent rounded-full animate-spin mb-3"></div>
        <span className="text-slate-600 text-sm font-medium">Loading persistent report snapshot...</span>
      </div>
    );
  }

  if (error || !report) {
    return (
      <div className="max-w-3xl mx-auto px-4 py-12 text-center">
        <div className="bg-rose-50 border border-rose-200 rounded-2xl p-8 flex flex-col items-center shadow-xs">
          <AlertCircle className="w-10 h-10 text-rose-600 mb-3" />
          <h2 className="text-lg font-bold text-slate-900 mb-1">Report Unavailable</h2>
          <p className="text-sm text-rose-800 max-w-md mb-6">{error || 'This report does not exist or you do not have permission to view it.'}</p>
          <Link
            to="/reports"
            className="px-4 py-2 bg-white hover:bg-slate-50 text-slate-800 text-xs font-semibold rounded-lg border border-slate-300 shadow-xs transition"
          >
            Back to Reports
          </Link>
        </div>
      </div>
    );
  }

  const { repository, metrics, findings, scope, workspace, createdBy, generatedAt, reportingPeriodDays } = report;

  const getScoreColor = (score) => {
    if (score >= 75) return 'text-emerald-600';
    if (score >= 50) return 'text-amber-600';
    return 'text-rose-600';
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8 space-y-8">
      {/* Top Breadcrumb & Header */}
      <div>
        <button
          onClick={() => navigate(-1)}
          className="inline-flex items-center gap-1.5 text-xs font-semibold text-slate-600 hover:text-slate-900 mb-4 transition"
        >
          <ArrowLeft className="w-4 h-4" />
          Back
        </button>

        <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-4 border-b border-slate-200 pb-6">
          <div>
            <div className="flex items-center gap-3 flex-wrap">
              <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-slate-900 flex items-center gap-2">
                <FileText className="w-7 h-7 text-emerald-600" />
                Health Report Snapshot
              </h1>

              {scope === 'workspace' ? (
                <span className="inline-flex items-center gap-1 text-xs uppercase font-bold tracking-wider px-2.5 py-0.5 rounded-full bg-blue-50 text-blue-700 border border-blue-200">
                  <Shield className="w-3.5 h-3.5" />
                  Workspace: {workspace?.name || 'Team Workspace'}
                </span>
              ) : (
                <span className="inline-flex items-center gap-1 text-xs uppercase font-bold tracking-wider px-2.5 py-0.5 rounded-full bg-emerald-50 text-emerald-700 border border-emerald-200">
                  <User className="w-3.5 h-3.5" />
                  Personal Report
                </span>
              )}
            </div>

            <div className="flex items-center gap-3 text-xs text-slate-500 mt-2 flex-wrap">
              <span className="font-bold text-slate-900">{repository.fullName}</span>
              <a
                href={repository.url}
                target="_blank"
                rel="noopener noreferrer"
                className="text-emerald-700 hover:underline flex items-center gap-1 font-semibold"
              >
                <span>View on GitHub</span>
                <ExternalLink className="w-3 h-3" />
              </a>
              <span className="text-slate-300">•</span>
              <span>Generated by {createdBy?.name || 'User'}</span>
              <span className="text-slate-300">•</span>
              <span className="flex items-center gap-1">
                <Clock className="w-3.5 h-3.5 text-slate-400" />
                {new Date(generatedAt).toLocaleDateString()}{' '}
                {new Date(generatedAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
              </span>
            </div>
          </div>
        </div>
      </div>

      {/* Immutable Snapshot Notice Banner */}
      <div className="p-4 rounded-xl bg-slate-100 border border-slate-200 text-xs text-slate-600 flex items-center justify-between gap-4 shadow-xs">
        <div className="flex items-center gap-2">
          <Clock className="w-4 h-4 text-emerald-600 shrink-0" />
          <span>
            This is an <strong className="text-slate-900">immutable historical snapshot</strong> preserving the health metrics and bottleneck findings recorded on {new Date(generatedAt).toLocaleDateString()}.
          </span>
        </div>
        <span className="font-semibold text-slate-700 shrink-0">Period: {reportingPeriodDays} Days</span>
      </div>

      {/* Health Score Banner */}
      <div className="bg-white border border-slate-200 rounded-2xl p-6 sm:p-8 flex flex-col md:flex-row md:items-center justify-between gap-6 shadow-xs">
        <div className="flex items-start sm:items-center gap-5">
          <div className="w-16 h-16 rounded-2xl bg-slate-50 border border-slate-200 flex flex-col items-center justify-center shrink-0">
            <span className={`text-2xl font-black ${getScoreColor(metrics.healthScore)}`}>
              {metrics.healthScore}
            </span>
            <span className="text-[9px] uppercase tracking-wider text-slate-400 font-bold">/ 100</span>
          </div>

          <div>
            <div className="flex items-center gap-2.5">
              <h2 className="text-lg font-bold text-slate-900">Snapshot Health Score</h2>
              <span className={`text-xs font-semibold px-2.5 py-0.5 rounded-full border ${
                metrics.healthScore >= 75
                  ? 'bg-emerald-50 text-emerald-800 border-emerald-200'
                  : metrics.healthScore >= 50
                  ? 'bg-amber-50 text-amber-800 border-amber-200'
                  : 'bg-rose-50 text-rose-800 border-rose-200'
              }`}>
                {metrics.healthStatus}
              </span>
            </div>
            <p className="text-xs text-slate-600 mt-1 max-w-xl">
              Historical record of pull request turnaround velocity, issue backlog, and commit activity.
            </p>
          </div>
        </div>

        <div className="flex items-center gap-6 border-t md:border-t-0 md:border-l border-slate-200 pt-4 md:pt-0 md:pl-8 text-xs text-slate-600">
          <div>
            <div className="text-slate-500 uppercase text-[10px] font-semibold">Findings Flagged</div>
            <div className="text-slate-900 font-bold text-base mt-0.5">{findings?.length || 0}</div>
          </div>
          <div>
            <div className="text-slate-500 uppercase text-[10px] font-semibold">Critical Bottlenecks</div>
            <div className="text-rose-600 font-bold text-base mt-0.5">{metrics.criticalFindingsCount || 0}</div>
          </div>
        </div>
      </div>

      {/* Vitals Grid */}
      <div>
        <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 mb-4">
          Recorded Vitals
        </h3>

        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-5 gap-4">
          <MetricCard
            title="Open Issues"
            value={metrics.openIssuesCount}
            subtitle="At time of snapshot"
            icon={AlertCircle}
            color="amber"
          />

          <MetricCard
            title="Open PRs"
            value={metrics.openPullRequestsCount}
            subtitle="Pending integration"
            icon={GitPullRequest}
            color="blue"
          />

          <MetricCard
            title="Merged PRs"
            value={metrics.mergedPullRequestsCount}
            subtitle="Within 30d window"
            icon={CheckCircle2}
            color="emerald"
          />

          <MetricCard
            title="Avg Merge Time"
            value={`${metrics.averagePRMergeTimeHours}h`}
            subtitle="Turnaround velocity"
            icon={Clock}
            color="purple"
          />

          <MetricCard
            title="Recent Commits"
            value={metrics.recentCommitsCount}
            subtitle="Default branch activity"
            icon={GitCommit}
            color="rose"
          />
        </div>
      </div>

      {/* Bottlenecks Snapshot */}
      <div>
        <h3 className="text-base font-bold text-slate-900 mb-4 flex items-center gap-2">
          <AlertTriangle className="w-5 h-5 text-amber-600" />
          Recorded Bottlenecks Snapshot ({findings?.length || 0})
        </h3>
        <FindingsSection findings={findings} />
      </div>
    </div>
  );
};
